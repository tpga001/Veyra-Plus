#include "veyra/engine/BrowserPreviewTypes.h"
#include <iostream>
#include <limits>
int main(){
    using namespace veyra::engine;
    unsigned checks=0,failures=0;
    const auto check=[&](bool pass,const char* name){++checks;if(!pass){++failures;std::cerr<<"FAIL "<<name<<'\n';}};
    const BrowserPreviewRequest running{100,11,3,true};
    check(browserPreviewRequestMatches(running,11),"matching visible session may request preview");
    check(!browserPreviewRequestMatches(running,12),"old session may not preview a newly opened source");
    auto request=running;request.visible=false;
    check(!browserPreviewRequestMatches(request,11),"hidden target does not authorize draw");
    request=running;request.window=0;
    check(!browserPreviewRequestMatches(request,11),"missing HWND does not authorize draw");
    request=running;request.sessionId=0;
    check(!browserPreviewRequestMatches(request,0),"empty session is not an authority");
    request=running;request.revision=0;
    check(!browserPreviewRequestMatches(request,11),"unversioned request is rejected");
    check(browserPreviewRevisionAccepted({},running),"first versioned request accepted");
    check(browserPreviewRevisionAccepted(running,running),"exact request replay is harmless");
    request=running;request.revision=2;
    check(!browserPreviewRevisionAccepted(running,request),"late UI request cannot replace newer request");
    request=running;request.visible=false;
    check(!browserPreviewRevisionAccepted(running,request),"same version may not mutate visibility");
    request=running;request.window=200;
    check(!browserPreviewRevisionAccepted(running,request),"same version may not mutate target");
    request=running;request.sessionId=12;
    check(!browserPreviewRevisionAccepted(running,request),"same version may not bind a new session");
    request={0,0,4,false};
    check(browserPreviewRevisionAccepted(running,request),"new version can revoke preview");
    check(browserPreviewCompletionMatches(running,running),"same request may publish completion");
    request=running;request.window=200;
    check(!browserPreviewCompletionMatches(request,running),"old target completion is discarded");
    request=running;request.sessionId=12;
    check(!browserPreviewCompletionMatches(request,running),"old media completion is discarded");
    request=running;request.revision=4;
    check(!browserPreviewCompletionMatches(request,running),"old request completion is discarded");
    check(!browserPreviewFrameReady(running,running,8,9,true),"GPU command submission is not completion");
    check(!browserPreviewFrameReady(running,running,9,9,false),"GPU completion without successful Present is not visible proof");
    check(browserPreviewFrameReady(running,running,9,9,true),"completed successful Present may publish frame");
    check(!browserPreviewFrameReady(running,running,9,0,true),"missing signal cannot publish frame");
    check(!browserPreviewFrameReady(running,running,std::numeric_limits<uint64_t>::max(),9,true),"device-removed fence sentinel is not completion");
    check(!browserPreviewFrameReady(request,running,9,9,true),"completed stale request remains rejected");
    check(browserPreviewGenerationMatches(2,7,40,2,7,40),"first frame of current graph generation is admitted");
    check(browserPreviewGenerationMatches(2,7,40,2,7,45),"same-generation later real frame is admitted");
    check(!browserPreviewGenerationMatches(2,7,40,1,7,45),"completed previous scene epoch cannot revive preview");
    check(!browserPreviewGenerationMatches(2,7,40,2,6,45),"completed previous settings cannot revive preview");
    check(!browserPreviewGenerationMatches(2,7,40,2,7,39),"same-number epoch/revision pre-transaction frame is rejected");
    check(!browserPreviewGenerationMatches(2,0,40,2,0,40),"unknown graph settings do not authorize completion");
    check(browserPreviewGenerationMatches(0,7,40,0,7,40),"graph epoch zero is valid when explicitly known");
    request=running;request.comparisonMode=2;
    check(browserPreviewNeedsReferences(request,11),"legal current visible wipe needs source references");
    check(!browserPreviewNeedsReferences(running,11),"enhanced preview does not retain source references");
    check(!browserPreviewNeedsReferences(request,12),"stale compare session may not add graph work");
    request.visible=false;
    check(!browserPreviewNeedsReferences(request,11),"hidden compare target adds no reference retention");
    request=running;request.comparisonMode=1;request.comparisonSplit=0.0f;
    check(browserPreviewComparisonValid(request),"original accepts lower split endpoint");
    request.comparisonSplit=1.0f;
    check(browserPreviewComparisonValid(request),"original accepts upper split endpoint");
    request.comparisonSplit=-.001f;
    check(!browserPreviewComparisonValid(request),"negative split is rejected");
    request.comparisonSplit=1.001f;
    check(!browserPreviewComparisonValid(request),"oversized split is rejected");
    request.comparisonSplit=std::numeric_limits<float>::quiet_NaN();
    check(!browserPreviewComparisonValid(request)&&!browserPreviewRevisionAccepted({},request),"NaN split cannot authorize or revise a request");
    request.comparisonSplit=std::numeric_limits<float>::infinity();
    check(!browserPreviewComparisonValid(request),"infinite split is rejected");
    request=running;request.comparisonMode=-1;
    check(!browserPreviewComparisonValid(request),"negative comparison mode is rejected");
    request.comparisonMode=3;
    check(!browserPreviewComparisonValid(request),"unknown comparison mode is rejected");
    request=running;request.comparisonMode=1;
    check(!browserPreviewRevisionAccepted(running,request),"same revision cannot change comparison mode");
    check(!browserPreviewCompletionMatches(request,running),"same revision altered mode cannot publish pixels");
    request=running;request.comparisonSplit=.25f;
    check(!browserPreviewRevisionAccepted(running,request),"same revision cannot change wipe position");
    check(!browserPreviewCompletionMatches(request,running),"same revision altered split cannot publish pixels");
    request=running;request.comparisonMode=2;request.comparisonSplit=.25f;++request.revision;
    check(browserPreviewRevisionAccepted(running,request),"new revision can change secondary mode and split");
    check(!browserPreviewFrameReady(request,running,9,9,true),"old enhanced completion cannot light new wipe request");
    check(browserPreviewFrameReady(request,request,9,9,true),"matching completed wipe request can publish pixels");
    const BrowserPreviewSnapshot cold;
    check(!cold.hasFrame&&!cold.live&&cold.submitted==0&&cold.gpuCompleted==0,"cold initialization does not claim pixels");
    std::cout<<"Browser preview policy checks="<<checks<<" failures="<<failures<<'\n';
    return failures?1:0;
}
